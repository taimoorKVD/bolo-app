use std::fs;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-env-changed=BOLO_BUILTIN_GROQ_KEY");
    emit_builtin_key();
    tauri_build::build();
}

/// Read `BOLO_BUILTIN_GROQ_KEY` while this script runs and write XOR bytes to
/// `OUT_DIR`. The application crate includes that file and never the key.
///
/// `option_env!("BOLO_BUILTIN_GROQ_KEY")` is the wrong read here. The macro
/// expands when *this build script* is compiled, so a later `cargo build` with
/// the variable set would keep the old value, and the same macro in the
/// application crate would leave a plaintext `&'static str` in `cadence.exe`.
/// `std::env::var` is the build-script equivalent: it sees the variable for
/// this build, and only the XOR'd bytes are emitted.
fn emit_builtin_key() {
    let raw = std::env::var("BOLO_BUILTIN_GROQ_KEY").unwrap_or_default();
    let key = raw.trim();
    // Fixed mask. Not a secret; it only keeps the key from showing up as a
    // contiguous string. Never print `key`.
    let mask: [u8; 16] = [
        0xA7, 0x3C, 0x91, 0x5E, 0x12, 0xD4, 0x6B, 0x88, 0x0F, 0xC2, 0x47, 0xE9, 0x5A, 0x31, 0xB6,
        0x74,
    ];
    let obfuscated: Vec<u8> = if key.is_empty() {
        Vec::new()
    } else {
        key.bytes()
            .enumerate()
            .map(|(index, byte)| byte ^ mask[index % mask.len()])
            .collect()
    };
    let out_dir = std::env::var_os("OUT_DIR").expect("OUT_DIR");
    let path = PathBuf::from(out_dir).join("builtin_key.rs");
    let mut body = String::from("// Generated by build.rs. Do not commit. XOR bytes only.\n");
    body.push_str("pub(crate) static BUILTIN_OBFUSCATED: &[u8] = &[\n");
    for (index, byte) in obfuscated.iter().enumerate() {
        if index % 12 == 0 {
            body.push_str("    ");
        }
        body.push_str(&format!("0x{byte:02X},"));
        if index % 12 == 11 || index + 1 == obfuscated.len() {
            body.push('\n');
        } else {
            body.push(' ');
        }
    }
    body.push_str("];\npub(crate) static BUILTIN_MASK: &[u8] = &[\n    ");
    for (index, byte) in mask.iter().enumerate() {
        body.push_str(&format!("0x{byte:02X}"));
        if index + 1 != mask.len() {
            body.push_str(", ");
        }
    }
    body.push_str("\n];\n");
    fs::write(&path, body).expect("write builtin_key.rs");
}
